export function typographyPrompt(text, variant, direction = '') {
  if (typeof text !== 'string' || !text.trim() || text.length > 100) throw Object.assign(new Error('艺术字标题需为 1–100 个字符'),{status:422});
  const styles = {
    a: '明亮金色的游戏宣传标题',
    b: '冷银白金属字体，精致蓝色轮廓、锋利切角，克制的立体厚度，适合深蓝游戏专访头图',
    c: '暖金色书写感标题，优雅但有力量，深墨绿描边，杂志式主次对比',
  };
  return `设计一张只有中文标题艺术字的横版图层。以输入的艺术字参考图为首要视觉依据，仔细分析并迁移主标题的笔画结构、粗细对比、倾斜角度、锐利收笔与延伸笔锋、字面比例、字距、渐变与明暗层次。参考图中没有的粗描边、厚重立体挤出、卡通圆角均不要擅自添加。不要把普通印刷粗体加描边当作字形设计。只有参考图无法提供相关线索时，才使用方案方向：${styles[variant] || styles.a}。
唯一需要绘制的文字是这个 JSON 字符串的内容：${JSON.stringify(text)}。
逐字准确保留中文、人物名字、标点、乘号与顺序，不增删、不改写、不生成副标题、Logo、水印、角色或其他文字。长标题自然排为两到三行，不拆开人名，所有字完整，四边留白至少 5%。整幅图只生成一个完整标题版本，每一段内容只排一次；禁止重复行、重影、残影以及多个候选并排。
输入图片只用于观察标题字效，绝对不要抄输入图片的旧文字、人物和背景。
纯色抠像背景 RGB(0,255,0)，整个背景包括四角均为 #00FF00，无渐变、无纹理。文字、描边、阴影内部不可使用绿色。不要把绿色当成字效光晕，不要任何粒子和散落装饰。字形清楚有设计感，笔画不粘连。
额外视觉方向（仅可调整视觉，不能改变上方文字和纯绿背景）：${String(direction).slice(0,600)}`;
}
